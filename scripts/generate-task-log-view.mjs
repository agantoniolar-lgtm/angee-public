#!/usr/bin/env node
/**
 * generate-task-log-view.mjs — a summary of where a task stands, one file per task.
 *
 * ── What it is ───────────────────────────────────────────────────────────────────────
 * `logs/tasks/<task-id>.md` only grows. After three review rounds it is two hundred fifty
 * lines, and the question anyone actually has — where is this task — costs reading all of
 * them. This writes the answer to `logs/tasks/current/<task-id>.md`.
 *
 * ── Why it summarizes instead of filtering ───────────────────────────────────────────
 * The first version of this view showed every entry nothing had closed, in full. Measured
 * on T054: 176 lines against the task log's 252. Notes, review rounds and approved case
 * lists have nothing that ever closes them, so they stayed forever and the view grew with
 * the task log. A view that costs what the original costs is a view nobody opens, and then
 * everyone reads the whole file again.
 *
 * So the view is not a filter, it is a REPORT: one section per event type, each line
 * bounded (100 characters of quoted body, at most), and nothing copied whole. A new review
 * round adds its rows and about four lines, whatever the length of what was written. The
 * shape was approved by the project owner and is written down in
 * `ae-kit-templates/task-log-ontology.md`, under "What the view summarizes".
 *
 * Its own text is English, like every other thing the kit prints; the sentences it quotes
 * stay in the language the project writes its task logs in.
 *
 * ── Hiding is not deleting ───────────────────────────────────────────────────────────
 * Nothing is ever removed from the task log. What the summary leaves out stays exactly
 * where it was written. When the summary is not enough — and it is not meant to always be
 * enough — the task log is one file away, and the view says so.
 *
 * ── When it runs ─────────────────────────────────────────────────────────────────────
 * `session-log` generates the views when it closes a session, and `open-session`
 * regenerates before reading one. The pre-commit hook no longer rejects a stale view: the
 * only reader regenerates first, so between a close and the next open a stale view on disk
 * harms nobody. What the hook still rejects is a HAND-EDITED view (`--check-hand-edits`),
 * which is the case that really costs something: a file a person wrote that the next
 * generation would otherwise delete.
 *
 * Usage:  generate-task-log-view.mjs [repoRoot] [--check | --check-hand-edits]
 *         --check             don't write; exit 1 if disk differs from what would be generated
 *         --check-hand-edits  don't write; exit 1 only for a view nobody generated
 *
 * Exit codes:
 *   0 — the views are written (or, with a check, nothing blocking was found)
 *   1 — a view was hand-edited; or, with --check, one is missing or stale; or something is unwritable
 *   2 — this project has no logs/tasks/; there is nothing to generate
 *   3 — advisory: the module that reads the format is not installed here
 */

import { existsSync, readdirSync, readFileSync, writeFileSync, statSync, mkdirSync, unlinkSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const args = process.argv.slice(2);
const HAND_EDITS_ONLY = args.includes('--check-hand-edits');
const CHECK_ONLY = args.includes('--check') || HAND_EDITS_ONLY;
const root = args.find((a) => !a.startsWith('--')) ?? process.cwd();
const dir = join(root, 'logs', 'tasks');

if (!existsSync(dir) || !statSync(dir).isDirectory()) {
  console.log('  · This project does not keep task logs (there is no logs/tasks/). Nothing to generate.');
  process.exit(2);
}

let B;
try {
  B = await import(join(dirname(fileURLToPath(import.meta.url)), 'task-log.mjs'));
} catch {
  console.log('  · The half that reads the format (scripts/task-log.mjs) is not installed here,');
  console.log('    so the current view cannot be generated. Not a failure.');
  process.exit(3);
}

const MARKER = 'GENERATED by scripts/generate-task-log-view.mjs';
const header = (taskId) =>
  `<!-- ${MARKER} — do not hand-edit.\n` +
  `     A summary of logs/tasks/${taskId}.md. Regenerated from there; editing this file\n` +
  `     changes nothing and is lost on the next run. An entry is corrected by\n` +
  `     appending another one to the task log, never by touching this view. -->`;

// ── Quoting a body, in one bounded line ──────────────────────────────────────────────
// Every line of this view that quotes the task log passes through here, and that is what
// makes the view's size depend on the NUMBER of entries and not on their length.
const CAP = 100;

/**
 * The first sentence of a body, flattened to one line and capped.
 *
 * A sentence ends at a period followed by whitespace, so "0.36.0" is never cut in half —
 * there is no space inside it. "p. ej." does get cut at the space, and that is accepted:
 * the alternative is a list of abbreviations per language, which would be wrong somewhere.
 */
function firstSentence(body, cap = CAP) {
  let text = String(body ?? '').replace(/\r/g, '');
  // A line that looks like markup — a list bullet, a heading, a quote — would become
  // markup again once it is placed after "- " in this file, so the leading markers go.
  text = text.replace(/^[\s>#*\-+]+/, '');
  text = text.replace(/\s+/g, ' ').trim();
  const end = text.search(/\.(\s|$)/);
  if (end !== -1) text = text.slice(0, end + 1);
  // Backticks and pipes survive the cut only if they cannot damage what comes after: an
  // unbalanced backtick opens a code span that swallows the rest of the view, and a pipe
  // inside a table cell starts a column that is not there.
  if ((text.match(/`/g) ?? []).length % 2 === 1) text = text.replace(/`/g, '');
  text = text.replace(/```/g, '');
  const chars = Array.from(text); // by code point: a cut must not split an accent or an emoji
  if (chars.length > cap) text = `${chars.slice(0, cap - 1).join('').trimEnd()}…`;
  return text;
}

const cell = (s) => String(s).replace(/\|/g, '\\|');

/**
 * The view's text. Deterministic by construction: no timestamps, no counts of anything
 * outside the file, no iteration over a Map whose order could change. If this were not
 * byte-for-byte stable, every session would produce a diff nobody reads — and once the
 * diff is noise, the part that matters stops being reviewed too.
 */
function render(taskId, entries) {
  const g = B.linkAnalysis(entries);
  const out = [header(taskId), '', `# Where it stands — ${taskId}`, ''];

  if (!entries.length) {
    out.push('This task log has no entries yet.', '');
    return out.join('\n');
  }

  if (g.cycles.length) {
    // A loop is shown, not hidden. Two entries that close each other would otherwise both
    // disappear, and work that is still open would vanish from the only place anyone
    // looks. So the loop is named here, its members stay open, and the verifier says
    // which link to remove.
    out.push('> **There is a link cycle in this task log.** The entries in it are treated as open even');
    out.push('> though they claim to close each other — hiding them would make work that is still open disappear.');
    for (const loop of g.cycles) out.push(`> Cycle: ${loop.join(' → ')} → ${loop[0]}`);
    out.push('');
  }

  const ordered = [...entries].sort(B.entryOrder);
  // ── Who closes whom: one rule, in task-log.mjs, shared with integrate-unit.mjs ──────
  const { live, finalOf, statusOf: closed } = B.closures(entries, g);
  const liveOf = (type) => ordered.filter((e) => e.type === type && live(e));

  // ── Decisions ──────────────────────────────────────────────────────────────────────
  const decisions = liveOf('decision');
  if (decisions.length) {
    out.push('## Decisions', '');
    for (const d of decisions) out.push(`- **${d.fields.by || '—'}** — ${firstSentence(d.body)}`);
    out.push('');
  }

  // ── Review rounds and what they found ──────────────────────────────────────────────
  // The round a finding belongs to is not a field: it is the last review round written
  // before it. If that round was later replaced, the finding moves to its replacement,
  // because the replacement IS that round.
  const liveRounds = liveOf('review-round');
  const roundNumber = new Map(liveRounds.map((r, i) => [r.id, i + 1]));
  const findings = [];
  let currentRound = null;
  for (const e of ordered) {
    if (e.type === 'review-round') { currentRound = e; continue; }
    if (e.type !== 'finding' || !live(e)) continue;
    const owner = currentRound ? finalOf(currentRound) : null;
    findings.push({ entry: e, round: owner && roundNumber.has(owner.id) ? roundNumber.get(owner.id) : null });
  }

  const statusOf = (e) => {
    const { status, closer } = closed(e);
    return { status, detail: status === 'dropped' ? firstSentence(closer.body) : '' };
  };
  const isBlocking = B.isBlocking;

  if (liveRounds.length || findings.length) {
    const blocking = findings.filter((f) => isBlocking(f.entry));
    const flags = findings.filter((f) => !isBlocking(f.entry));
    const fixedOf = (list) => list.filter((f) => statusOf(f.entry).status === 'fixed').length;
    out.push('## Review', '');
    // The totals come from counting the findings, never from the prose in a round's
    // `result:` — that field is written by hand and is exactly the thing that drifts.
    out.push(`${liveRounds.length} round(s) · ${blocking.length} blocking (${fixedOf(blocking)} fixed) · ` +
             `${flags.length} flag(s) (${fixedOf(flags)} fixed)`);
    for (const f of blocking) {
      const s = statusOf(f.entry);
      out.push(`- blocking, ${s.status}: ${firstSentence(f.entry.body)}`);
    }
    for (const f of flags) {
      const s = statusOf(f.entry);
      if (s.status === 'fixed') continue; // a fixed flag is in its round's table and nowhere else
      out.push(`- flag, ${s.status}: ${firstSentence(f.entry.body)}`);
    }
    out.push('');

    const groups = [];
    for (const f of findings) {
      let grp = groups.find((x) => x.round === f.round);
      if (!grp) { grp = { round: f.round, items: [] }; groups.push(grp); }
      grp.items.push(f);
    }
    groups.sort((a, b) => (a.round ?? 0) - (b.round ?? 0));
    for (const grp of groups) {
      const rows = grp.items.map((f) => ({ e: f.entry, ...statusOf(f.entry) }));
      const withDetail = rows.some((r) => r.detail);
      out.push(`### ${grp.round === null ? 'Before any round' : `Round ${grp.round}`}`, '');
      out.push(`| Severity | Finding | Status |${withDetail ? ' Detail |' : ''}`);
      out.push(`|---|---|---|${withDetail ? '---|' : ''}`);
      for (const r of rows) {
        out.push(`| ${cell(String(r.e.fields.severity ?? '—').trim())} | ${cell(firstSentence(r.e.body))} | ${r.status} |` +
                 (withDetail ? ` ${cell(r.detail)} |` : ''));
      }
      out.push('');
    }
  }

  // ── Adversarial cases ──────────────────────────────────────────────────────────────
  // One line per group, never per case: the approved list is what the task file and the
  // task log hold, and repeating thirty-four cases here is the copy this view exists to
  // stop. A group split into (1/2) and (2/2) is one group with its counts added.
  const caseEntries = liveOf('adversarial-cases');
  if (caseEntries.length) {
    const groups = [];
    const ownerCases = [];
    for (const e of caseEntries) {
      const firstLine = String(e.body ?? '').split('\n').find((l) => l.trim()) ?? '';
      const name = firstSentence(firstLine.replace(/\s*\(\d+\s*\/\s*\d+\)\s*$/, ''));
      let grp = groups.find((x) => x.name === name);
      if (!grp) { grp = { name, counts: [] }; groups.push(grp); }
      grp.counts.push(String(e.fields.count ?? '').trim());
      for (const line of String(e.body ?? '').split('\n')) {
        // Only `[owner]` at the start of the line, lower case. A marker that matched
        // anywhere would turn a sentence ABOUT the convention into a pending.
        const m = /^\[owner\][ \t]+([A-Za-z]+-\d+)\b[ \t]*(.*)$/.exec(line);
        if (m) ownerCases.push({ label: m[1], text: m[2], entry: e });
      }
    }
    const numeric = (c) => /^\d+$/.test(c);
    const allNumeric = groups.every((grp) => grp.counts.every(numeric));
    const total = allNumeric ? groups.reduce((n, grp) => n + grp.counts.reduce((m, c) => m + Number(c), 0), 0) : null;
    out.push('## Adversarial cases', '');
    out.push(`${groups.length} group(s) · ${total === null ? 'total not countable: a count is not a number' : `${total} case(s)`}`);
    for (const grp of groups) {
      const sum = grp.counts.every(numeric) ? String(grp.counts.reduce((m, c) => m + Number(c), 0)) : grp.counts.join(' + ');
      out.push(`- ${grp.name}: ${sum}`);
    }
    for (const c of ownerCases) {
      // Decided when a decision that still stands, written AFTER the case, cites its
      // number. Compared whole: a decision about "A-30" does not decide "A-3".
      const re = new RegExp(`(^|[^A-Za-z0-9-])${c.label}([^0-9-]|$)`);
      const decision = decisions.find((d) => B.entryOrder(d, c.entry) > 0 && re.test(String(d.body ?? '')));
      out.push(decision
        ? `- ${c.label} · owner's call, decided by ${decision.fields.by || '—'}`
        : `- ${c.label} · owner's call, pending${c.text ? ` — ${firstSentence(c.text)}` : ''}`);
    }
    out.push('');
  }

  // ── Measurements ───────────────────────────────────────────────────────────────────
  const measurements = liveOf('measurement');
  if (measurements.length) {
    out.push('## Measurements', '');
    for (const m of measurements) out.push(`- ${firstSentence(m.fields.metric, 60)}: ${firstSentence(m.fields.value, 60)}`);
    out.push('');
  }

  // ── Notes ──────────────────────────────────────────────────────────────────────────
  // Counted, never quoted. A note is what somebody wrote for the record; if the count says
  // there are nine and this summary does not explain something, the task log has them.
  const notes = liveOf('note').length;
  out.push(`${notes} note(s) and the full history: \`logs/tasks/${taskId}.md\` (${entries.length} entry(ies)).`, '');
  return out.join('\n');
}

// ── Where the views live, and what is left of the old layout ─────────────────────────
const NOISE = /^(\.DS_Store|Thumbs\.db|\.gitkeep|\.keep|desktop\.ini)$/i;
const targets = [];
const problems = [];
const legacy = [];     // views of the pre-0.36.0 layout, generated: to be retired
const orphans = [];    // views in current/ whose task log is gone
const handEdited = []; // files with a view's name that nobody generated

const viewFolder = B.viewDir(root);
if (existsSync(viewFolder) && !statSync(viewFolder).isDirectory()) {
  console.error('  Current view\n');
  console.error(`  ✗ logs/tasks/${B.VIEW_DIR_NAME} is a file, and that name is the folder the views live in.`);
  console.error('      Nothing was touched. Move that file to docs/ (or delete it if it is an old view)');
  console.error('      and run this again.');
  process.exit(1);
}

const isGenerated = (path) => {
  try { return readFileSync(path, 'utf8').includes(MARKER); } catch { return false; }
};

for (const name of readdirSync(dir)) {
  if (NOISE.test(name) || name.endsWith('.lock')) continue;
  if (name === B.VIEW_DIR_NAME) continue; // the folder the views live in
  if (name.endsWith('.current.md')) {
    // The old layout. One generated by this script is retired; one a person wrote is
    // reported and never touched, the same refusal as always.
    const path = join(dir, name);
    (isGenerated(path) ? legacy : handEdited).push({ label: `logs/tasks/${name}`, path });
    continue;
  }
  if (!name.endsWith('.md')) continue;
  const taskId = name.slice(0, -3);
  let text;
  try { text = readFileSync(join(dir, name), 'utf8'); }
  catch { problems.push(`could not read logs/tasks/${name}`); continue; }
  const { entries } = B.parseTaskLog(text);
  targets.push({ taskId, path: B.viewPath(root, taskId), content: render(taskId, entries) });
}

const wanted = new Set(targets.map((t) => t.taskId));
if (existsSync(viewFolder)) {
  for (const name of readdirSync(viewFolder)) {
    if (NOISE.test(name) || name.endsWith('.lock')) continue;
    const path = join(viewFolder, name);
    if (!isGenerated(path)) { handEdited.push({ label: `logs/tasks/${B.VIEW_DIR_NAME}/${name}`, path }); continue; }
    if (!name.endsWith('.md') || !wanted.has(name.slice(0, -3))) {
      orphans.push({ label: `logs/tasks/${B.VIEW_DIR_NAME}/${name}`, path });
    }
  }
}

// ── Write, or check ──────────────────────────────────────────────────────────────────
const stale = [];
for (const t of targets) {
  let onDisk = null;
  if (existsSync(t.path)) {
    try { onDisk = readFileSync(t.path, 'utf8'); } catch { onDisk = null; }
  }
  if (onDisk !== t.content) stale.push(t);
}

// A file with a view's name that this script did not generate is not a stale view — it is
// somebody's work, and overwriting it would destroy it without asking. Reported, never
// clobbered, and this is the one thing the pre-commit hook still blocks on.
if (handEdited.length) {
  console.error('  Current view\n');
  for (const t of handEdited) {
    console.error(`  ✗ ${t.label} exists and was not generated by this script.`);
    console.error(`      That name is reserved for the generated view. If the file is yours, move it`);
    console.error('      to docs/; if it is an old view, delete it and run the generator again.\n');
  }
  process.exit(1);
}

if (HAND_EDITS_ONLY) {
  const behind = stale.length + legacy.length + orphans.length;
  console.log(`✓ ${targets.length} current view(s): none hand-edited` +
              (behind ? ` (${behind} to regenerate; session-log and open-session do that)` : ''));
  process.exit(0);
}

if (CHECK_ONLY) {
  const lines = [];
  for (const t of stale) {
    lines.push(`  ✗ logs/tasks/${B.VIEW_DIR_NAME}/${t.taskId}.md ${existsSync(t.path) ? 'does not match its task log' : 'does not exist'}.`);
  }
  for (const t of legacy) lines.push(`  ✗ ${t.label} is a view of the old layout and would be retired.`);
  for (const t of orphans) lines.push(`  ✗ ${t.label} has no task log and would be deleted.`);
  if (lines.length) {
    console.error('  Current view\n');
    for (const l of lines) console.error(l);
    console.error('\n  This view is generated, not written by hand. Run:');
    console.error('      node scripts/generate-task-log-view.mjs');
    console.error('  A view that updates when somebody remembers is a view nobody trusts.');
    process.exit(1);
  }
  console.log(`✓ ${targets.length} current view(s) up to date.`);
  process.exit(0);
}

if (targets.length && !existsSync(viewFolder)) {
  try { mkdirSync(viewFolder, { recursive: true }); }
  catch (e) { problems.push(`could not create logs/tasks/${B.VIEW_DIR_NAME}/: ${e.message}`); }
}

for (const t of stale) {
  try { writeFileSync(t.path, t.content); }
  catch (e) { problems.push(`could not write logs/tasks/${B.VIEW_DIR_NAME}/${t.taskId}.md: ${e.message}`); }
}
const retired = [];
for (const t of [...legacy, ...orphans]) {
  try { unlinkSync(t.path); retired.push(t.label); }
  catch (e) { problems.push(`could not delete ${t.label}: ${e.message}`); }
}

if (problems.length) {
  for (const p of problems) console.error(`  ✗ ${p}`);
  process.exit(1);
}
for (const label of retired) console.log(`  · retired ${label}`);
console.log(`✓ ${targets.length} current view(s) (${stale.length} rewritten${retired.length ? `, ${retired.length} retired` : ''}).`);
process.exit(0);
